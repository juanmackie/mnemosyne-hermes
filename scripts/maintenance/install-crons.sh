#!/usr/bin/env bash
# Register (or remove) the Mnemosyne maintenance jobs in Hermes cron.
#
# Idempotent: every job is looked up by name before it is created, so re-running
# this after an update repairs missing jobs and never duplicates the ones that
# are already there. Nothing is created with --dry-run.
#
# Usage:
#   scripts/maintenance/install-crons.sh                 # install what is missing
#   scripts/maintenance/install-crons.sh --dry-run       # print the plan only
#   scripts/maintenance/install-crons.sh --list          # show job state
#   scripts/maintenance/install-crons.sh --uninstall     # remove our jobs
#
# Environment:
#   HERMES_HOME        Hermes home (default: ~/.hermes)
#   HERMES_BIN         Hermes CLI (default: hermes on PATH)
#   PYTHON_BIN         interpreter for the maintenance script (default: python3)
#   MNEMOSYNE_CRON_DELIVER  delivery target for notices (default: leave to Hermes)
set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
MAINTAIN="$REPO/scripts/maintenance/mnemosyne-maintain.py"
HERMES_HOME="${HERMES_HOME:-$HOME/.hermes}"
HERMES_BIN="${HERMES_BIN:-hermes}"
PYTHON_BIN="${PYTHON_BIN:-}"
SCRIPTS_DIR="$HERMES_HOME/scripts"
DELIVER_ARGS=()
[[ -n "${MNEMOSYNE_CRON_DELIVER:-}" ]] && DELIVER_ARGS=(--deliver "$MNEMOSYNE_CRON_DELIVER")

DRY_RUN=false
MODE=install
for arg in "$@"; do
  case "$arg" in
  --dry-run) DRY_RUN=true ;;
  --list) MODE=list ;;
  --uninstall) MODE=uninstall ;;
  -h | --help)
    sed -n '2,20p' "$0"
    exit 0
    ;;
  *)
    printf 'Unknown option: %s\n' "$arg" >&2
    exit 2
    ;;
  esac
done

[[ -f "$MAINTAIN" ]] || {
  printf 'Error: maintenance script not found at %s\n' "$MAINTAIN" >&2
  exit 1
}
command -v "$HERMES_BIN" >/dev/null 2>&1 || {
  printf 'Error: %s not found. Set HERMES_BIN or put hermes on PATH.\n' "$HERMES_BIN" >&2
  exit 1
}

# Prefer the interpreter Hermes itself runs on: it is the one most likely to see
# the pinned engine, and the maintenance script uses its own venv to find the
# engine CLI. Fall back to python3 when that cannot be resolved.
if [[ -z "$PYTHON_BIN" ]]; then
  hermes_path="$(command -v "$HERMES_BIN")"
  # Walk the symlink chain, checking each hop's directory: Hermes is often
  # installed as ~/.local/bin/hermes -> <venv>/bin/hermes -> ../libexec/hermes,
  # and only the middle hop sits next to the venv's python.
  link="$hermes_path"
  for _ in 1 2 3 4; do
    hop_dir="$(dirname "$link")"
    for candidate in "$hop_dir/python3" "$hop_dir/python"; do
      if [[ -x "$candidate" ]]; then
        PYTHON_BIN="$candidate"
        break 2
      fi
    done
    [[ -L "$link" ]] || break
    target="$(readlink "$link")"
    case "$target" in
    /*) link="$target" ;;
    *) link="$hop_dir/$target" ;;
    esac
  done
  PYTHON_BIN="${PYTHON_BIN:-python3}"
fi

# name | schedule | maintenance subcommand | wrapper suffix
JOBS=(
  "mnemosyne-backup|30 2 * * *|backup --keep 14|daily snapshot, verified, 14 retained"
  "mnemosyne-consolidate|20 21 * * *|consolidate|working -> episodic -> BEAM tiers"
  "mnemosyne-verify|10 3 * * 0|verify --full|weekly full integrity check"
  "mnemosyne-hygiene|40 3 * * 0|hygiene|weekly noise audit, report only"
  "mnemosyne-compact|30 3 1 * *|compact|monthly VACUUM above freelist threshold"
)

job_field() { printf '%s' "$1" | cut -d'|' -f"$2"; }

existing_jobs() {
  "$HERMES_BIN" cron list 2>/dev/null || true
}

job_exists() {
  # Names are short enough that Hermes never truncates them in `cron list`.
  existing_jobs | grep -Fq "Name:      $1"
}

job_id() {
  existing_jobs | awk -v name="$1" '
    /^[[:space:]]*[0-9a-f]{12} \[/ { id = $1 }
    /^[[:space:]]*Name:/ { sub(/^[[:space:]]*Name:[[:space:]]*/, ""); if ($0 == name) { print id; exit } }
  '
}

write_wrapper() {
  local name="$1" subcommand="$2"
  local wrapper="$SCRIPTS_DIR/$name.sh"
  local body="#!/usr/bin/env bash
# Generated by mnemosyne-hermes scripts/maintenance/install-crons.sh
# Re-run that script after moving the checkout.
set -euo pipefail
exec \"$PYTHON_BIN\" \"$MAINTAIN\" $subcommand --hermes-home \"$HERMES_HOME\" \"\$@\""
  if [[ -f "$wrapper" ]] && [[ "$(cat "$wrapper")" == "$body" ]]; then
    return 0
  fi
  if [[ "$DRY_RUN" == true ]]; then
    printf '  would write %s\n' "$wrapper"
    return 0
  fi
  mkdir -p "$SCRIPTS_DIR"
  printf '%s\n' "$body" >"$wrapper"
  chmod +x "$wrapper"
}

if [[ "$MODE" == list ]]; then
  printf 'Job                                State\n'
  for entry in "${JOBS[@]}"; do
    name="$(job_field "$entry" 1)"
    if job_exists "$name"; then state=present; else state=MISSING; fi
    printf '%-34s %s\n' "$name" "$state"
  done
  exit 0
fi

if [[ "$MODE" == uninstall ]]; then
  for entry in "${JOBS[@]}"; do
    name="$(job_field "$entry" 1)"
    id="$(job_id "$name")"
    if [[ -z "$id" ]]; then
      printf '%-34s not installed\n' "$name"
      continue
    fi
    if [[ "$DRY_RUN" == true ]]; then
      printf '  would remove %s (%s) and %s/%s.sh\n' "$name" "$id" "$SCRIPTS_DIR" "$name"
      continue
    fi
    "$HERMES_BIN" cron remove "$id" >/dev/null
    rm -f "$SCRIPTS_DIR/$name.sh"
    printf '%-34s removed (%s)\n' "$name" "$id"
  done
  exit 0
fi

printf 'Mnemosyne maintenance — %s\n' "$REPO"
printf 'Hermes home: %s\n' "$HERMES_HOME"
printf 'Interpreter: %s\n' "$PYTHON_BIN"
# Show the database the jobs will actually touch. A wrong home is otherwise
# invisible until a backup contains somebody else's memories.
db_line="$("$PYTHON_BIN" "$MAINTAIN" report --hermes-home "$HERMES_HOME" 2>&1 | head -n 1)"
printf 'Database:    %s\n\n' "${db_line:-unresolved}"

created=0
for entry in "${JOBS[@]}"; do
  name="$(job_field "$entry" 1)"
  schedule="$(job_field "$entry" 2)"
  subcommand="$(job_field "$entry" 3)"
  description="$(job_field "$entry" 4)"

  if job_exists "$name"; then
    printf '%-34s present  %s\n' "$name" "$schedule"
    # Repair a stale wrapper (checkout moved, interpreter changed) even though
    # the job itself is already registered.
    write_wrapper "$name" "$subcommand"
    continue
  fi
  printf '%-34s create   %s  (%s)\n' "$name" "$schedule" "$description"
  write_wrapper "$name" "$subcommand"
  if [[ "$DRY_RUN" == true ]]; then
    printf '  would run: %s cron create "%s" --no-agent --script %s.sh --name %s %s\n' \
      "$HERMES_BIN" "$schedule" "$name" "$name" "${DELIVER_ARGS[*]:-}"
    continue
  fi
  "$HERMES_BIN" cron create "$schedule" --no-agent --script "$name.sh" --name "$name" "${DELIVER_ARGS[@]}" >/dev/null
  created=$((created + 1))
done

if [[ "$DRY_RUN" == true ]]; then
  printf '\nDry run: no jobs were created.\n'
  exit 0
fi

# Verify against the scheduler, not against our own exit code.
missing=0
for entry in "${JOBS[@]}"; do
  name="$(job_field "$entry" 1)"
  job_exists "$name" || {
    printf 'VERIFY FAILED: %s is not in `hermes cron list`\n' "$name" >&2
    missing=$((missing + 1))
  }
done
if [[ "$missing" -gt 0 ]]; then
  exit 1
fi
printf '\n%d job(s) created; all %d present in `hermes cron list`.\n' "$created" "${#JOBS[@]}"
printf 'Run one now to prove the path: %s cron run %s\n' "$HERMES_BIN" "mnemosyne-verify"
